#!/usr/bin/env ruby
# generate_commands.rb: regenerates skills/messengerr/references/commands.md from
# the REAL CLI's own output, so the reference cannot drift from the binary.
#
#   MESSENGERR_BIN="messengerr" ruby build/generate_commands.rb
#
# The CLI version it was generated from is recorded in .messengerr-version; CI
# installs exactly that version and fails if regenerating changes the file.
# credentials are inspected with an empty throwaway config dir so output never
# depends on the machine it runs on.
require "open3"
require "shellwords"
require "tmpdir"

ROOT = File.expand_path("..", __dir__)
OUT = File.join(ROOT, "skills/messengerr/references/commands.md")
VERSION_FILE = File.join(ROOT, ".messengerr-version")
BIN = Shellwords.split(ENV.fetch("MESSENGERR_BIN", "messengerr"))

def run(*args, ok: [ 0 ])
  out, err, status = Dir.mktmpdir do |config|
    env = { "MESSENGERR_CONFIG_DIR" => config, "MESSENGERR_MASTER_KEY" => nil, "LC_ALL" => "C.UTF-8" }
    Open3.capture3(env, *BIN, *args)
  end
  abort("generate_commands: `messengerr #{args.join(' ')}` exited #{status.exitstatus}: #{err}") unless ok.include?(status.exitstatus)
  out.force_encoding(Encoding::UTF_8).strip
end

version = run("--version")
abort("generate_commands: unexpected --version output #{version.inspect}") unless version.match?(/\A\d+\.\d+\.\d+\z/)

doc = <<~MD
  # messengerr command reference

  <!-- GENERATED by build/generate_commands.rb from `messengerr` #{version}'s own output.
       Do not edit by hand: CI regenerates this file from that exact version and fails on any difference. -->

  Generated from **messengerr #{version}**.

  ## Top level

  ```
  #{run('--help')}
  ```

  ## credentials

  Run bare, the command prints its usage (and exits 1). Claude never runs `setup` or `delete`: the human does.

  ```
  #{run('credentials', ok: [ 1 ])}
  ```

  ## send

  ```
  #{run('send', '--help')}
  ```

  Most flags **answer a wizard question in advance**; anything left out is still asked. `dry_run.sh` never prompts, so give it every flag.

  Placeholders in the message and the subject each need a `--map placeholder=column`.

  ## integrations

  ```
  #{run('integrations')}
  ```

  (Shown with an empty configuration; on a real machine each integration says `configured` once its credentials are stored.)

  ## Exit codes

  | Code | Meaning |
  |---|---|
  | `0` | Everything was sent, or a `--dry-run` completed. |
  | `1` | Some sends failed, the run was aborted, or an error stopped it (printed as `messengerr: ...`). |
  | `130` | The send was interrupted with Ctrl-C. The ledger and a `--resume` command are printed. |

  ## The send guard

  A send that is not a `--dry-run` is refused unless standard input is an interactive terminal:

  ```
  messengerr: refusing to send without an interactive terminal: run `messengerr send` yourself in a terminal (or pass --allow-non-interactive in your own scripts). --dry-run works anywhere.
  ```

  That is the intended behaviour for Claude and for CI: Claude prepares and previews, the human sends. `--allow-non-interactive` exists for the human's own scripts and is never used by this skill.
MD

File.write(OUT, doc)
File.write(VERSION_FILE, "#{version}\n")
puts "wrote #{OUT} (from messengerr #{version})"
